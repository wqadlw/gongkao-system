def _module_tree_text(module):
    """生成某模块的分类树文本（缩进列表），用于在提示词中告知 AI 可选考点。"""
    cats = get_categories_data()
    by_parent = {}
    for c in cats:
        by_parent.setdefault(c["parent_id"], []).append(c)
    lines = []

    def walk(pid, depth):
        for c in by_parent.get(pid, []):
            if c.get("level1") != module:
                continue
            lines.append("    " * depth + "- " + c["name"])
            walk(c["id"], depth + 1)

    root = next((c for c in cats if c["level"] == 1 and c["level1"] == module), None)
    if root:
        lines.append("- " + root["name"])
        walk(root["id"], 1)
    return "\n".join(lines)


def _full_tree_text(max_depth=4):
    """生成压缩版题型树文本（到 max_depth 层），用于在通用提示词中告知 AI 可选考点。"""
    cats = get_categories_data()
    by_parent = {}
    for c in cats:
        by_parent.setdefault(c["parent_id"], []).append(c)
    lines = []
    def walk(pid, depth):
        if depth > max_depth:
            return
        for c in by_parent.get(pid, []):
            lines.append("    " * (depth - 1) + "- " + c["name"])
            walk(c["id"], depth + 1)
    for c in cats:
        if c["level"] == 1:
            lines.append("- " + c["name"])
            walk(c["id"], 2)
    return "\n".join(lines)


